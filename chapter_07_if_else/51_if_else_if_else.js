// if, else if, and else are used when there are multiple conditions to check.

let marks = 75;

if (marks >= 90) {
  console.log("Grade: A");
} else if (marks >= 75) {
  console.log("Grade: B");
} else if (marks >= 50) {
  console.log("Grade: C");
} else {
  console.log("Grade: F");
}

// Example with temperature
let temperature = 30;

if (temperature > 35) {
  console.log("Very hot");
} else if (temperature >= 20) {
  console.log("Warm");
} else {
  console.log("Cold");
}
