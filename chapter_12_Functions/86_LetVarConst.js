//VAR LET CONST IN JS
//1. var: Function-scoped variable, can be re-declared and updated.
var myVar = "Hello, World!";
console.log(myVar); // Output: Hello, World!

//2. let: Block-scoped variable, can be updated but not re-declared in the same scope.
let myLet = "Hello, Let!";
console.log(myLet); // Output: Hello, Let!

//3. const: Block-scoped variable, cannot be updated or re-declared.
const myConst = "Hello, Const!";
console.log(myConst); // Output: Hello, Const!